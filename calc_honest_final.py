def g_star(T):
    """Число релятивистских степеней свободы."""
    if T > 300: return 106.75
    if T > 100: return 86.25
    if T > 1:   return 75.0
    if T > 0.2: return 61.75
    if T > 0.1: return 51.25
    if T > 0.001: return 10.75
    return 3.36


def H_T(T):
    """H² = 8πρ/(3 M_Pl²) с ПОЛНОЙ массой Планка."""
    rho = np.pi**2 / 30 * g_star(T) * T**4
    return np.sqrt(8 * np.pi * rho / (3 * M_PL_FULL**2))


def m_a_T(T, m_a_0):
    """T-зависимая масса аксиона."""
    if T < LAMBDA_QCD:
        return m_a_0
    return m_a_0 * (LAMBDA_QCD / T)**4


def find_T_osc(m_a_0):
    """T_osc из условия m_a(T) = 3H(T)."""
    def f(T):
        return m_a_T(T, m_a_0) - 3 * H_T(T)
    try:
        return brentq(f, LAMBDA_QCD * 1.1, 100.0)
    except ValueError:
        return None


def omega_axion(f_a, theta_i=1.0):
    """Ω_a h² через misalignment."""
    m_a_0 = LAMBDA_QCD**2 / f_a
    T_osc = find_T_osc(m_a_0)
    if T_osc is None:
        return None
    m_a_osc = m_a_T(T_osc, m_a_0)
    g_s_osc = g_star(T_osc)
    a_ratio = (T_0 / T_osc) * (G_STAR_S_0 / g_s_osc)**(1/3)
    rho_a_0 = 0.5 * m_a_0 * m_a_osc * f_a**2 * theta_i**2 * a_ratio**3
    return rho_a_0 / RHO_CRIT_H2


